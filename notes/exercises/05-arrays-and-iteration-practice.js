// Practice: Arrays and Iteration
// 1. Create an array of 3 numbers.
// 2. Use map to double each value.
// 3. Use filter to find numbers greater than 10.

const nums = [2, 4, 6];
const doubled = nums.map((n) => n * 2);
const filtered = nums.filter((n) => n > 2);

console.log(nums);
console.log(doubled);
console.log(filtered);
