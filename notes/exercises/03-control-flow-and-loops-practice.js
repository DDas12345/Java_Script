// Practice: Control Flow and Loops
// 1. Write an if/else for a score.
// 2. Loop from 0 to 4 using for.
// 3. Use while to count to 3.

let score = 80;
if (score >= 75) {
  console.log("Pass");
} else {
  console.log("Fail");
}

for (let i = 0; i < 5; i++) {
  console.log(i);
}

let count = 0;
while (count < 3) {
  console.log("Count:", count);
  count++;
}
