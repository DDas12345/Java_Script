// Operators and Expressions in JavaScript

// Arithmetic operators
const a = 10;
const b = 3;
console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);
console.log(a ** b);

// Assignment operators
let total = 5;
total += 10;
total *= 2;
console.log("Total:", total);

// Comparison operators
console.log(5 == "5");
console.log(5 === "5");
console.log(10 > 7);
console.log(10 >= 10);
console.log(3 < 5);

// Logical operators
const isUser = true;
const isAdmin = false;
console.log(isUser && isAdmin);
console.log(isUser || isAdmin);
console.log(!isAdmin);

// String expressions
const firstName = "Ash";
const lastName = "Ketchum";
console.log(firstName + " " + lastName);

// Ternary operator
const age = 18;
console.log(age >= 18 ? "Adult" : "Minor");

// Expressions are values or combinations of values and operators.
